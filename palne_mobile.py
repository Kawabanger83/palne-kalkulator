# ===== ВИБІР АВТО =====
st.subheader("1. Вибір автомобіля")

brand = st.selectbox("Марка", list(cars_by_brand.keys()))
model = st.selectbox("Модель", list(cars_by_brand[brand].keys()))

if brand == "Власна норма":
    Hs = st.number_input("Базова норма Hs (л/100 км)", min_value=1.0, value=8.0, step=0.1)
else:
    Hs = cars_by_brand[brand][model]
    st.success(f"**{brand} {model}** — {Hs} л/100 км")

S = st.number_input("Пробіг (км)", min_value=0.0, value=100.0, step=1.0)

# ===== УМОВИ ЕКСПЛУАТАЦІЇ =====
st.subheader("2. Умови експлуатації")

winter = st.selectbox("Зимова надбавка", [
    "0% — без надбавки",
    "2% — 0°C до -5°C",
    "4% — -5°C до -10°C",
    "6% — -10°C до -15°C",
    "8% — -15°C до -20°C",
    "10% — -20°C до -25°C",
    "12% — нижче -25°C"
])
winter_val = int(winter.split("%")[0])

city = st.selectbox("Місто (тип населеного пункту)", [
    "0% — не місто",
    "5% — невелике місто / селище",
    "10% — середнє місто",
    "15% — велике місто / інтенсивний рух"
])
city_val = int(city.split("%")[0])

traffic = st.selectbox("Затори", ["0%", "5%", "10%", "15%"])
ac = st.selectbox("Кондиціонер / клімат-контроль", ["0%", "5%", "7%", "10%"])
bad_road = st.selectbox("Погані дороги / бездоріжжя", ["0%", "10%", "20%", "30%", "35%"])
combat = st.selectbox("Зона бойових дій / під обстрілом", ["0%", "20%", "30%", "40%", "50%"])
mountain = st.selectbox("Гірська місцевість", ["0%", "5%", "10%", "15%", "20%"])
tech = st.selectbox("Технічний стан автомобіля", ["0%", "5%", "10%"])
highway = st.selectbox("Понижувальний коефіцієнт (траса)", ["0%", "-10%", "-15%", "-20%", "-25%", "-30%"])

K_sum = (winter_val + city_val +
         int(traffic.replace("%","")) +
         int(ac.replace("%","")) +
         int(bad_road.replace("%","")) +
         int(combat.replace("%","")) +
         int(mountain.replace("%","")) +
         int(tech.replace("%","")) +
         int(highway.replace("%","")))

st.info(f"**Сумарний коефіцієнт KΣ = {K_sum}%**")

if st.button("РОЗРАХУВАТИ", use_container_width=True):
    Qn = 0.01 * Hs * S * (1 + 0.01 * K_sum)
    st.success(f"### Нормативна витрата: **{Qn:.2f} л**")
    st.write(f"{brand} {model} | Пробіг {S} км | KΣ = {K_sum}%")

