# ===== ВИБІР АВТО =====
st.subheader("1. Вибір автомобіля")

brand = st.selectbox("Оберіть марку", list(cars_by_brand.keys()))

models = cars_by_brand[brand]
model = st.selectbox("Оберіть модель", list(models.keys()))

if brand == "Власна норма":
    Hs = st.number_input("Базова норма Hs (л/100 км)", min_value=1.0, value=8.0, step=0.1)
else:
    Hs = models[model]
    st.success(f"**{brand} {model}** — {Hs} л/100 км")

S = st.number_input("Пробіг (км)", min_value=0.0, value=100.0, step=1.0)

# ===== УМОВИ ЕКСПЛУАТАЦІЇ =====
st.subheader("2. Умови експлуатації (з Методики)")

st.markdown("**Зимова надбавка (залежить від температури)**")
winter = st.selectbox(
    "Оберіть діапазон температури",
    [
        "Без надбавки (0%)",
        "0°C до -5°C (+2%)",
        "-5°C до -10°C (+4%)",
        "-10°C до -15°C (+6%)",
        "-15°C до -20°C (+8%)",
        "-20°C до -25°C (+10%)",
        "нижче -25°C (+12%)"
    ]
)
winter_val = int(winter.split("+")[-1].replace("%)", "")) if "+" in winter else 0

st.markdown("**Місто (залежно від населеного пункту)**")
city = st.selectbox(
    "Тип населеного пункту",
    [
        "Не місто (0%)",
        "Невелике місто / селище (+5%)",
        "Середнє місто (+10%)",
        "Велике місто / інтенсивний рух (+15%)"
    ]
)
city_val = int(city.split("+")[-1].replace("%)", "")) if "+" in city else 0

k_traffic = st.slider("Затори (додатково)", 0, 10, 0, help="Додаткова надбавка за сильні затори")
k_ac = st.slider("Кондиціонер / клімат-контроль", 0, 10, 0, help="У теплу пору року до +10%")
k_bad = st.slider("Погані дороги / бездоріжжя", 0, 35, 0, help="До +35%")
k_combat = st.slider("Зона бойових дій / рух під обстрілом", 0, 50, 0, help="До +50% згідно з Методикою")
k_mountain = st.slider("Гірська місцевість", 0, 20, 0, help="Залежно від висоти до +20%")
k_tech = st.slider("Технічний стан автомобіля", 0, 10, 0, help="Спрацьованість, великий пробіг")
k_highway = st.slider("Понижувальний коефіцієнт (траса)", -30, 0, 0, help="Для трас і автомагістралей")

K_sum = winter_val + city_val + k_traffic + k_ac + k_bad + k_combat + k_mountain + k_tech + k_highway

st.info(f"**Сумарний коефіцієнт KΣ = {K_sum}%**")

# ===== ДОВІДКА =====
with st.expander("📋 Роз’яснення коефіцієнтів згідно з Методикою"):
    st.markdown("""
**Зима (п. 3.1.1):**
- 0°C…-5°C → до 2%
- -5°C…-10°C → до 4%
- -10°C…-15°C → до 6%
- -15°C…-20°C → до 8%
- -20°C…-25°C → до 10%
- нижче -25°C → до 12%

**Місто:**
- Невелике місто → до 5%
- Середнє місто → до 10%
- Велике місто / інтенсивний рух → до 15%

**Інші надбавки:**
- Погані дороги / бездоріжжя → до 35%
- Зона бойових дій / під обстрілом → до **50%**
- Гірська місцевість → до 20%
- Кондиціонер → до 10%
- Технічний стан → до 10%

**Понижувальний (траса):** від -5% до -30%
    """)

# ===== РОЗРАХУНОК =====
if st.button("РОЗРАХУВАТИ", use_container_width=True, type="primary"):
    Qn = 0.01 * Hs * S * (1 + 0.01 * K_sum)
    st.success(f"### Нормативна витрата **Qн = {Qn:.2f} л**")
    st.write(f"{brand} {model} | Пробіг: {S} км | KΣ: {K_sum}%")

